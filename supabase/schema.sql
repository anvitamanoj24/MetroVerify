-- Enable UUID generation
create extension if not exists "uuid-ossp";

-- ─────────────────────────────────────────────
-- 1. PROFILES  (extends Supabase auth.users)
-- ─────────────────────────────────────────────
create table public.profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  full_name     text not null,
  email         text not null,
  phone         text,
  role          text not null check (role in ('merchant','officer','gatc','admin')),
  organisation  text,
  state         text,
  district      text,
  is_active     boolean default true,
  created_at    timestamptz default now(),
  updated_at    timestamptz default now()
);

-- Auto-insert profile row when a new user signs up
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer as $$
begin
  insert into public.profiles (id, full_name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    new.email,
    coalesce(new.raw_user_meta_data->>'role', 'merchant')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- ─────────────────────────────────────────────
-- 2. INSTRUMENTS
-- ─────────────────────────────────────────────
create table public.instruments (
  id              uuid primary key default uuid_generate_v4(),
  owner_id        uuid not null references public.profiles(id) on delete cascade,
  name            text not null,
  instrument_type text not null,
  serial_number   text not null unique,
  seal_id         text unique,
  manufacturer    text,
  model           text,
  capacity        text,
  unit            text default 'kg',
  address         text,
  district        text,
  state           text,
  status          text default 'unverified'
                    check (status in ('unverified','valid','expiring','expired','under_review')),
  created_at      timestamptz default now(),
  updated_at      timestamptz default now()
);

-- ─────────────────────────────────────────────
-- 3. APPLICATIONS
-- ─────────────────────────────────────────────
create table public.applications (
  id              uuid primary key default uuid_generate_v4(),
  app_number      text unique,           -- e.g. APP-2026-0412 (generated by trigger)
  instrument_id   uuid not null references public.instruments(id) on delete cascade,
  applicant_id    uuid not null references public.profiles(id),
  assigned_to     uuid references public.profiles(id),  -- LMO / GATC officer
  pathway         text not null check (pathway in ('digital','physical')),
  status          text default 'submitted'
                    check (status in (
                      'submitted','under_review','evidence_requested',
                      'approved','escalated','rejected'
                    )),
  fee_amount      numeric(10,2),
  fee_paid        boolean default false,
  notes           text,
  remarks         text,                  -- officer remarks
  submitted_at    timestamptz default now(),
  reviewed_at     timestamptz,
  created_at      timestamptz default now(),
  updated_at      timestamptz default now()
);

-- Auto-generate readable application number
create or replace function public.generate_app_number()
returns trigger language plpgsql as $$
begin
  new.app_number := 'APP-' || to_char(now(), 'YYYY') || '-' ||
                    lpad(nextval('app_number_seq')::text, 4, '0');
  return new;
end;
$$;

create sequence if not exists app_number_seq start 1000;

create trigger set_app_number
  before insert on public.applications
  for each row execute procedure public.generate_app_number();

