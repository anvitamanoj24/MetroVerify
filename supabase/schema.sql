-- ── Profiles ──
create policy "Users can read own profile"
  on public.profiles for select
  using (auth.uid() = id);

create policy "Users can update own profile"
  on public.profiles for update
  using (auth.uid() = id);

create policy "Admins can read all profiles"
  on public.profiles for select
  using (
    exists (
      select 1 from public.profiles
      where id = auth.uid() and role = 'admin'
    )
  );

-- ── Instruments ──
create policy "Merchants can manage own instruments"
  on public.instruments for all
  using (owner_id = auth.uid());

create policy "Officers can read all instruments"
  on public.instruments for select
  using (
    exists (
      select 1 from public.profiles
      where id = auth.uid() and role in ('officer','gatc','admin')
    )
  );

-- ── Applications ──
create policy "Merchants can manage own applications"
  on public.applications for all
  using (applicant_id = auth.uid());

create policy "Officers can read and update applications"
  on public.applications for select
  using (
    exists (
      select 1 from public.profiles
      where id = auth.uid() and role in ('officer','gatc','admin')
    )
  );

create policy "Officers can update assigned applications"
  on public.applications for update
  using (
    assigned_to = auth.uid()
    or exists (
      select 1 from public.profiles
      where id = auth.uid() and role in ('admin')
    )
  );

-- ── Evidence ──
create policy "Applicant can manage own evidence"
  on public.evidence for all
  using (uploaded_by = auth.uid());

create policy "Officers can view evidence"
  on public.evidence for select
  using (
    exists (
      select 1 from public.profiles
      where id = auth.uid() and role in ('officer','gatc','admin')
    )
  );

-- ── Certificates ──
create policy "Owners can view own certificates"
  on public.certificates for select
  using (issued_to = auth.uid());

create policy "Officers can manage certificates"
  on public.certificates for all
  using (
    exists (
      select 1 from public.profiles
      where id = auth.uid() and role in ('officer','gatc','admin')
    )
  );

-- Public certificate lookup (no auth needed) – for QR verify page
create policy "Public can read certificates by cert_number"
  on public.certificates for select
  using (true);

-- ── Notifications ──
create policy "Users can manage own notifications"
  on public.notifications for all
  using (user_id = auth.uid());

-- ── Enforcement ──
create policy "Admins and officers can manage enforcement"
  on public.enforcement_cases for all
  using (
    exists (
      select 1 from public.profiles
      where id = auth.uid() and role in ('officer','admin')
    )
  );

-- ── Scheduled Inspections ──
create policy "Officers can manage their inspections"
  on public.scheduled_inspections for all
  using (
    officer_id = auth.uid()
    or exists (
      select 1 from public.profiles
      where id = auth.uid() and role = 'admin'
    )
  );

create policy "Merchants can view inspections for their applications"
  on public.scheduled_inspections for select
  using (
    exists (
      select 1 from public.applications a
      where a.id = application_id
        and a.applicant_id = auth.uid()
    )
  );

-- ─────────────────────────────────────────────
-- 12. UPDATED_AT AUTO-UPDATE TRIGGER
-- ─────────────────────────────────────────────
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger trg_profiles_updated_at
  before update on public.profiles
  for each row execute procedure public.set_updated_at();

create trigger trg_instruments_updated_at
  before update on public.instruments
  for each row execute procedure public.set_updated_at();

create trigger trg_applications_updated_at
  before update on public.applications
  for each row execute procedure public.set_updated_at();

create trigger trg_enforcement_updated_at
  before update on public.enforcement_cases
  for each row execute procedure public.set_updated_at();

