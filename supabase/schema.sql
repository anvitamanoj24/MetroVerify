-- ─────────────────────────────────────────────
-- 6. CERTIFICATES
-- ─────────────────────────────────────────────
create table public.certificates (
  id              uuid primary key default uuid_generate_v4(),
  cert_number     text unique,           -- e.g. MV-2026-TN-004521
  application_id  uuid not null references public.applications(id),
  instrument_id   uuid not null references public.instruments(id),
  issued_to       uuid not null references public.profiles(id),
  issued_by       uuid not null references public.profiles(id),
  verification_method text not null check (verification_method in ('digital','physical')),
  issued_at       timestamptz default now(),
  valid_from      date not null,
  valid_until     date not null,
  is_revoked      boolean default false,
  revoked_at      timestamptz,
  qr_payload      text,                  -- cryptographic payload for QR
  pdf_url         text,
  created_at      timestamptz default now()
);

-- Auto-generate readable certificate number
create or replace function public.generate_cert_number()
returns trigger language plpgsql as $$
declare
  state_code text;
begin
  select coalesce(substr(upper(i.state), 1, 2), 'IN')
    into state_code
    from public.instruments i
    where i.id = new.instrument_id;

  new.cert_number := 'MV-' || to_char(now(), 'YYYY') || '-' || state_code || '-' ||
                     lpad(nextval('cert_number_seq')::text, 6, '0');
  return new;
end;
$$;

create sequence if not exists cert_number_seq start 1000;

create trigger set_cert_number
  before insert on public.certificates
  for each row execute procedure public.generate_cert_number();

-- When a certificate is issued, update instrument status to 'valid'
create or replace function public.on_certificate_issued()
returns trigger language plpgsql as $$
begin
  update public.instruments
    set status = 'valid', updated_at = now()
    where id = new.instrument_id;

  update public.applications
    set status = 'approved', reviewed_at = now(), updated_at = now()
    where id = new.application_id;

  return new;
end;
$$;

create trigger after_certificate_issued
  after insert on public.certificates
  for each row execute procedure public.on_certificate_issued();

