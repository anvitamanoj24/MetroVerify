-- Applications with instrument + applicant joined
create or replace view public.applications_view as
select
  a.*,
  i.name            as instrument_name,
  i.instrument_type,
  i.serial_number,
  i.capacity,
  i.unit,
  i.district        as instrument_district,
  i.state           as instrument_state,
  p.full_name       as applicant_name,
  p.email           as applicant_email,
  p.phone           as applicant_phone,
  p.organisation    as applicant_org
from public.applications a
join public.instruments  i on i.id = a.instrument_id
join public.profiles     p on p.id = a.applicant_id;

-- Certificates with all related data joined
create or replace view public.certificates_view as
select
  c.*,
  i.name            as instrument_name,
  i.instrument_type,
  i.serial_number,
  i.seal_id,
  i.capacity,
  i.unit,
  i.manufacturer,
  i.model,
  i.address,
  i.district        as instrument_district,
  i.state           as instrument_state,
  p_owner.full_name  as owner_name,
  p_owner.organisation as owner_org,
  p_officer.full_name as officer_name
from public.certificates c
join public.instruments  i        on i.id = c.instrument_id
join public.profiles     p_owner  on p_owner.id = c.issued_to
join public.profiles     p_officer on p_officer.id = c.issued_by;

